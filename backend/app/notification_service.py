"""
In-app Smart Notifications: fan-out to active students with idempotent dedupe keys.

No email/SMS/push. Deadline reminders are generated by process_deadline_reminders()
(startup + background poll + lazy on student notification reads).
"""
from __future__ import annotations

import logging
import threading
from datetime import date, datetime, timedelta, timezone
from typing import Any

from app.database import get_conn, now_iso

logger = logging.getLogger(__name__)

NOTIFICATION_TYPES = frozenset({
    "document_new",
    "document_superseded",
    "calendar_new",
    "calendar_updated",
    "calendar_cancelled",
    "deadline_reminder",
})

# Categories that warrant approaching-deadline reminders.
DEADLINE_CATEGORIES = frozenset({
    "Fee Deadlines",
    "Registration Deadlines",
    "Examinations",
    "Placement Drives",
})

# Remind N calendar days before the event start date (inclusive day-of = 0).
REMINDER_OFFSET_DAYS = (3, 1, 0)

_reminder_thread: threading.Thread | None = None
_reminder_stop = threading.Event()
_REMINDER_INTERVAL_SECONDS = 15 * 60


def list_active_student_ids(conn=None) -> list[int]:
    def _q(c):
        rows = c.execute(
            """SELECT id FROM users
               WHERE role = 'student' AND COALESCE(account_status, 'active') = 'active'
               ORDER BY id"""
        ).fetchall()
        return [int(r["id"] if hasattr(r, "keys") else r[0]) for r in rows]

    if conn is not None:
        return _q(conn)
    with get_conn() as c:
        return _q(c)


def fan_out_to_students(
    *,
    title: str,
    message: str,
    notification_type: str,
    dedupe_key: str,
    related_document_id: int | None = None,
    related_event_id: int | None = None,
) -> int:
    """
    Insert one notification row per active student.
    Uses INSERT OR IGNORE on (user_id, dedupe_key) so restarts / retries are safe.
    Returns number of newly inserted rows.
    """
    if notification_type not in NOTIFICATION_TYPES:
        raise ValueError(f"Unknown notification_type: {notification_type}")
    title = (title or "").strip() or "Campus update"
    message = (message or "").strip() or title
    dedupe_key = (dedupe_key or "").strip()
    if not dedupe_key:
        raise ValueError("dedupe_key is required")

    created = now_iso()
    inserted = 0
    with get_conn() as conn:
        student_ids = list_active_student_ids(conn)
        if not student_ids:
            return 0
        for uid in student_ids:
            cur = conn.execute(
                """INSERT OR IGNORE INTO notifications (
                       user_id, title, message, notification_type,
                       related_document_id, related_event_id, dedupe_key, created_at, read_at
                   ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, NULL)""",
                (
                    uid,
                    title,
                    message,
                    notification_type,
                    related_document_id,
                    related_event_id,
                    dedupe_key,
                    created,
                ),
            )
            inserted += cur.rowcount
    return inserted


def notify_document_published(doc: dict[str, Any]) -> int:
    """Notify students when a document becomes ready + active for them."""
    status = (doc.get("document_status") or "active").lower()
    processing = (doc.get("processing_status") or "").lower()
    if status != "active" or processing != "ready":
        return 0
    # Skip obvious non-notice smoke / admin probe uploads.
    title = (doc.get("title") or "").strip()
    filename = (doc.get("filename") or "").strip().lower()
    if "gemini_activation_smoke" in filename or "activation_smoke" in title.lower():
        return 0

    category = (doc.get("category") or "General").strip()
    desc_bits = []
    if category:
        desc_bits.append(f"Category: {category}.")
    if doc.get("department"):
        desc_bits.append(f"Department: {doc['department']}.")
    message = " ".join(desc_bits) if desc_bits else "A new university notice is available."
    if doc.get("document_type"):
        message = f"{message} Type: {doc['document_type']}."

    return fan_out_to_students(
        title=f"New notice: {title}",
        message=message.strip(),
        notification_type="document_new",
        dedupe_key=f"document_new:{int(doc['id'])}",
        related_document_id=int(doc["id"]),
    )


def notify_document_superseded(
    newer: dict[str, Any],
    older: dict[str, Any] | None,
) -> int:
    """Notify when an active ready document supersedes an older notice."""
    status = (newer.get("document_status") or "active").lower()
    processing = (newer.get("processing_status") or "").lower()
    if status != "active" or processing != "ready":
        return 0
    if older is None:
        return 0
    older_title = (older.get("title") or "previous notice").strip()
    newer_title = (newer.get("title") or "Updated notice").strip()
    category = (newer.get("category") or "").strip()
    message = (
        f"“{newer_title}” replaces “{older_title}”."
        + (f" Category: {category}." if category else "")
    )
    return fan_out_to_students(
        title=f"Notice updated: {newer_title}",
        message=message,
        notification_type="document_superseded",
        dedupe_key=f"document_superseded:{int(newer['id'])}:{int(older['id'])}",
        related_document_id=int(newer["id"]),
    )


def _format_event_when(event: dict[str, Any]) -> str:
    start = event.get("start_datetime") or ""
    loc = (event.get("location") or "").strip()
    parts = [start[:16].replace("T", " ")] if start else []
    if loc:
        parts.append(f"at {loc}")
    return " ".join(parts) if parts else "see calendar"


def notify_calendar_published(event: dict[str, Any]) -> int:
    if (event.get("publication_status") or "") != "published":
        return 0
    # Seed inserts bypass create_event; still guard if called with seed_key demos on create.
    title = (event.get("title") or "Campus event").strip()
    cat = (event.get("category") or "").strip()
    when = _format_event_when(event)
    message = f"{cat + ': ' if cat else ''}{when}."
    if event.get("description"):
        message = f"{message} {(event['description'] or '')[:160]}"
    src = event.get("source_document_id")
    return fan_out_to_students(
        title=f"New calendar event: {title}",
        message=message.strip(),
        notification_type="calendar_new",
        dedupe_key=f"calendar_new:{int(event['id'])}",
        related_event_id=int(event["id"]),
        related_document_id=int(src) if src is not None else None,
    )


def notify_calendar_updated(before: dict[str, Any], after: dict[str, Any]) -> int:
    before_status = before.get("publication_status") or ""
    after_status = after.get("publication_status") or ""

    # Newly published
    if before_status != "published" and after_status == "published":
        return notify_calendar_published(after)

    # Unpublished / cancelled for students
    if before_status == "published" and after_status != "published":
        return notify_calendar_cancelled(before)

    if after_status != "published":
        return 0

    material_keys = ("title", "start_datetime", "end_datetime", "location", "category", "description")
    changed = [k for k in material_keys if before.get(k) != after.get(k)]
    if not changed:
        return 0

    title = (after.get("title") or "Campus event").strip()
    when = _format_event_when(after)
    message = f"Updated fields: {', '.join(changed)}. Now scheduled {when}."
    # Include updated_at so each distinct admin save notifies once, not on every poll.
    dedupe = f"calendar_updated:{int(after['id'])}:{after.get('updated_at') or now_iso()}"
    src = after.get("source_document_id")
    return fan_out_to_students(
        title=f"Calendar updated: {title}",
        message=message,
        notification_type="calendar_updated",
        dedupe_key=dedupe,
        related_event_id=int(after["id"]),
        related_document_id=int(src) if src is not None else None,
    )


def notify_calendar_cancelled(event: dict[str, Any]) -> int:
    """Call only for events that were visible to students (published)."""
    title = (event.get("title") or "Campus event").strip()
    return fan_out_to_students(
        title=f"Event cancelled: {title}",
        message="This event is no longer on the student calendar.",
        notification_type="calendar_cancelled",
        dedupe_key=f"calendar_cancelled:{int(event['id'])}",
        related_event_id=int(event["id"]),
    )


def _parse_event_date(start_datetime: str) -> date | None:
    if not start_datetime:
        return None
    raw = str(start_datetime).strip()
    try:
        # Date-only or ISO with timezone / offset.
        if len(raw) >= 10 and raw[4] == "-" and raw[7] == "-":
            return date(int(raw[0:4]), int(raw[5:7]), int(raw[8:10]))
    except (TypeError, ValueError):
        return None
    return None


def process_deadline_reminders(*, today: date | None = None) -> int:
    """
    Create idempotent deadline reminders for published deadline-like events.
    Safe to call repeatedly (unique dedupe_key per user/event/offset).
    """
    today = today or datetime.now(timezone.utc).date()
    total = 0
    with get_conn() as conn:
        rows = conn.execute(
            """SELECT id, title, description, category, start_datetime, location,
                      publication_status, source_document_id
               FROM academic_events
               WHERE publication_status = 'published'
                 AND category IN ({})
            """.format(",".join("?" for _ in DEADLINE_CATEGORIES)),
            tuple(sorted(DEADLINE_CATEGORIES)),
        ).fetchall()

    for row in rows:
        event = dict(row)
        event_date = _parse_event_date(event.get("start_datetime") or "")
        if event_date is None:
            continue
        for offset in REMINDER_OFFSET_DAYS:
            if today != event_date - timedelta(days=offset):
                continue
            eid = int(event["id"])
            title = (event.get("title") or "Deadline").strip()
            when = _format_event_when(event)
            if offset == 0:
                headline = f"Today: {title}"
                body = f"This {event.get('category')} is scheduled for today ({when})."
            elif offset == 1:
                headline = f"Tomorrow: {title}"
                body = f"Reminder — {event.get('category')} is tomorrow ({when})."
            else:
                headline = f"In {offset} days: {title}"
                body = f"Upcoming {event.get('category')} on {when}."
            src = event.get("source_document_id")
            total += fan_out_to_students(
                title=headline,
                message=body,
                notification_type="deadline_reminder",
                dedupe_key=f"deadline_reminder:{eid}:d{offset}",
                related_event_id=eid,
                related_document_id=int(src) if src is not None else None,
            )
    return total


def start_deadline_reminder_scheduler() -> None:
    """Daemon thread: periodic deadline reminder scan. Idempotent start."""
    global _reminder_thread
    if _reminder_thread is not None and _reminder_thread.is_alive():
        return

    def _loop():
        while not _reminder_stop.wait(_REMINDER_INTERVAL_SECONDS):
            try:
                n = process_deadline_reminders()
                if n:
                    logger.info("Deadline reminders inserted: %s", n)
            except Exception:  # noqa: BLE001 — never kill the scheduler
                logger.exception("Deadline reminder scan failed")

    _reminder_stop.clear()
    _reminder_thread = threading.Thread(
        target=_loop,
        name="campus-deadline-reminders",
        daemon=True,
    )
    _reminder_thread.start()
    # Immediate scan so Docker restarts catch same-day deadlines without waiting.
    try:
        process_deadline_reminders()
    except Exception:  # noqa: BLE001
        logger.exception("Initial deadline reminder scan failed")


def list_notifications_for_user(
    user_id: int,
    *,
    limit: int = 30,
    offset: int = 0,
    unread_only: bool = False,
) -> tuple[list[dict[str, Any]], int, int]:
    """
    Returns (items, total_matching, unread_count).
    Lazy-triggers deadline reminders so students see them without waiting for the thread.
    """
    try:
        process_deadline_reminders()
    except Exception:  # noqa: BLE001
        logger.exception("Lazy deadline reminder scan failed")

    limit = max(1, min(int(limit), 100))
    offset = max(0, int(offset))
    with get_conn() as conn:
        unread_count = conn.execute(
            """SELECT COUNT(*) AS n FROM notifications
               WHERE user_id = ? AND read_at IS NULL""",
            (user_id,),
        ).fetchone()["n"]
        where = "user_id = ?"
        params: list[Any] = [user_id]
        if unread_only:
            where += " AND read_at IS NULL"
        total = conn.execute(
            f"SELECT COUNT(*) AS n FROM notifications WHERE {where}",
            params,
        ).fetchone()["n"]
        rows = conn.execute(
            f"""SELECT id, user_id, title, message, notification_type,
                       related_document_id, related_event_id, created_at, read_at
                FROM notifications
                WHERE {where}
                ORDER BY created_at DESC, id DESC
                LIMIT ? OFFSET ?""",
            [*params, limit, offset],
        ).fetchall()
    items = [dict(r) for r in rows]
    for item in items:
        item["is_read"] = item.get("read_at") is not None
    return items, int(total), int(unread_count)


def unread_count_for_user(user_id: int) -> int:
    try:
        process_deadline_reminders()
    except Exception:  # noqa: BLE001
        logger.exception("Lazy deadline reminder scan failed")
    with get_conn() as conn:
        return int(
            conn.execute(
                """SELECT COUNT(*) AS n FROM notifications
                   WHERE user_id = ? AND read_at IS NULL""",
                (user_id,),
            ).fetchone()["n"]
        )


def mark_notification_read(user_id: int, notification_id: int) -> bool:
    with get_conn() as conn:
        row = conn.execute(
            "SELECT id, read_at FROM notifications WHERE id = ? AND user_id = ?",
            (notification_id, user_id),
        ).fetchone()
        if row is None:
            return False
        if row["read_at"] is None:
            conn.execute(
                "UPDATE notifications SET read_at = ? WHERE id = ? AND user_id = ?",
                (now_iso(), notification_id, user_id),
            )
        return True


def mark_all_notifications_read(user_id: int) -> int:
    with get_conn() as conn:
        cur = conn.execute(
            """UPDATE notifications SET read_at = ?
               WHERE user_id = ? AND read_at IS NULL""",
            (now_iso(), user_id),
        )
        return int(cur.rowcount)
